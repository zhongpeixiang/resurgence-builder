import { readFile, writeFile } from 'node:fs/promises';

const input = new URL('../imports/resurgence-os-protocols.html', import.meta.url);
const output = new URL('../data/os-protocols.js', import.meta.url);
const sourceUrl = 'https://resurgencebuilds.com/database/os-protocols/';

function decodeHtml(value) {
  return value
    .replace(/&amp;/g, '&')
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'")
    .replace(/&lt;/g, '<')
    .replace(/&gt;/g, '>')
    .replace(/\s+/g, ' ')
    .trim();
}

function text(html) {
  return decodeHtml(html.replace(/<[^>]+>/g, ' '));
}

function required(match, field, id) {
  if (!match?.[1]) throw new Error(`Missing ${field} for ${id}`);
  return text(match[1]);
}

const html = await readFile(input, 'utf8');
const cards = [...html.matchAll(/<a\s+href="\/database\/os-protocols\/([^"/]+)\/"[^>]*class="db-card-link"[^>]*>\s*(<article class="db-card[\s\S]*?<\/article>)\s*<\/a>/g)];
if (cards.length === 0) throw new Error('No OS Protocol cards found in source capture');

const protocols = cards.map(([, slug, card]) => {
  const name = required(card.match(/<h2 class="db-card__title">([\s\S]*?)<\/h2>/), 'name', slug);
  const tags = [...card.matchAll(/<span class="tag(?: [^"]*)?">([\s\S]*?)<\/span>/g)].map(match => text(match[1]));
  const rarity = card.match(/<span class="tag rarity-[^"]+">([\s\S]*?)<\/span>/)?.[1];
  const core = tags.find(tag => ['Engineering', 'Firepower', 'Toughness'].includes(tag));
  const talent = required(card.match(/<div class="db-card__talent">\s*<strong>Talent:<\/strong>([\s\S]*?)<\/div>/), 'talent', slug);
  const mainStat = {
    label: required(card.match(/<span class="main-stat-name">([\s\S]*?)<\/span>/), 'main stat label', slug),
    value: required(card.match(/<span class="main-stat-value">([\s\S]*?)<\/span>/), 'main stat value', slug)
  };
  const attributes = [...card.matchAll(/<li>\s*<span>([\s\S]*?)<\/span>\s*<span>([\s\S]*?)<\/span>\s*<\/li>/g)]
    .map(match => ({ label: text(match[1]), value: text(match[2]) }));
  const cooldown = card.match(/<div class="db-card__cooldown">([\s\S]*?)<\/div>/)?.[1];
  if (!core || !rarity || attributes.length !== 3) throw new Error(`Unexpected protocol shape for ${slug}`);
  return {
    id: `resurgencebuilds:os-protocol:${slug}`,
    name,
    type: 'OS Protocol',
    core,
    rarity: text(rarity),
    talent,
    cooldown: cooldown ? text(cooldown).replace(/^.*?\s(\d+ seconds)$/, '$1') : null,
    mainStat,
    attributes,
    source: sourceUrl,
    sourcePath: `/database/os-protocols/${slug}/`
  };
});

const ids = new Set(protocols.map(protocol => protocol.id));
if (ids.size !== protocols.length) throw new Error('Duplicate protocol IDs');
if (protocols.length !== 66) throw new Error(`Expected 66 protocols, found ${protocols.length}`);

await writeFile(output, `// Generated by scripts/import-os-protocols.mjs from ${sourceUrl}. Do not edit by hand.\nexport const protocolCatalog = ${JSON.stringify(protocols, null, 2)};\n`);
console.log(`Wrote ${protocols.length} OS Protocols to ${output.pathname}`);
